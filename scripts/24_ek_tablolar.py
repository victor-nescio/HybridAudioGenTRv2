"""
Ek dosya (Supplementary Material) tablolari S1-S8 — tumu kayitli ciktilardan uretilir (elle sayi yok).

  S1 taksonomi kurallari (src/data/labels.py)        S5 BEATs saglamlik analizi
  S2 ilk hedef seti (31 May-2 Haz 2026, results/v1)   S6 ezber analizi
  S3 promptlar (TR/EN)                                S7 sureklilik: en iyi-val/test, segment McNemar, v1 yeniden analiz
  S4 sinif basina gercek segment ve sentetik pay      S8 hesaplama maliyeti

Kullanim: python scripts/24_ek_tablolar.py  ->  results/v2/ek_tablolar.md
"""
import importlib.util
import json
from pathlib import Path

import numpy as np
from scipy.stats import chi2

ROOT = Path(__file__).resolve().parents[1]
EN = {  # ilk gonderimin Sekil 4'undeki adlar
    "ayak_sesleri": "footstep sounds", "at_sesleri": "horse sounds", "saat_can_sesleri": "clock/bell",
    "cocuk_bebek_sesleri": "children/baby", "kapi_sesleri": "door sounds", "ucak_sesleri": "aircraft sounds",
    "kara_tasitlari": "land vehicles", "gemi_tekne_sesleri": "ship/boat", "tren_sesleri": "train sounds",
    "ev_ici_sesler": "indoor sounds", "endustri_fabrika": "industry/factory", "kopek_sesleri": "dog sounds",
    "spor_eglence": "sports/entertainment", "ofis_iletisim": "office/communication", "kalabalik_sesleri": "crowd sounds",
    "silah_patlama": "weapon/explosion", "sehir_atmosferi": "city atmosphere", "kus_sesleri": "bird sounds",
    "acil_servis": "emergency service", "doga_atmosferi": "nature atmosphere", "diger_hayvanlar": "other animals",
    "su_sesleri": "water sounds", "hava_olaylari": "weather events", "tarim_ciftlik": "farm/livestock",
    "dini_mekan": "religious place", "insaat_sesleri": "construction",
}
AUG = ["kopek_sesleri", "kus_sesleri", "hava_olaylari", "insaat_sesleri", "dini_mekan", "tarim_ciftlik",
       "acil_servis", "diger_hayvanlar"]
KON = {"baseline": "baseline", "H1": "H1", "C2p": "C2′", "C3p": "C3′", "C4p": "C4′", "C4p_kaydir": "C4′-shift",
       "specaug": "SpecAugment", "specaugC4p": "SpecAugment + C4′", "beats_baseline": "BEATs baseline",
       "beats_H1": "BEATs H1", "beats_C4p": "BEATs C4′"}
GRUP = {"A_belirgin": "Group A", "B_dusukF1": "Group B", "B_faz1_acil": "emergency service", "kontrol": "control"}


def pfmt(p):
    """p-degeri: < 0.001 bilimsel gosterim (iki anlamli basamak), aksi halde uc ondalik."""
    return f"{p:.1e}" if p < 0.001 else f"{p:.3f}"


def _modul(ad, yol):
    s = importlib.util.spec_from_file_location(ad, yol)
    m = importlib.util.module_from_spec(s)
    s.loader.exec_module(m)
    return m


def tablo(baslik, satirlar):
    out = ["| " + " | ".join(baslik) + " |", "|" + "---|" * len(baslik)]
    out += ["| " + " | ".join(str(x) for x in s) + " |" for s in satirlar]
    return "\n".join(out)


def f(x, n=3, isaret=True):
    return (f"{x:+.{n}f}" if isaret else f"{x:.{n}f}").replace("-", "−")


def main():
    md = ["# Supplementary Material", "",
          "**Fine-Tuned CLAP-Guided Text-to-Audio Generative Augmentation for Environmental Sound Classification: "
          "A Controlled Multi-Configuration Evaluation**", "",
          "Fatih Doğan Cellat and Fatma Noyan Tekeli", "",
          "All tables are generated by `scripts/24_ek_tablolar.py` from the stored outputs in the public repository "
          "(https://github.com/victor-nescio/HybridAudioGenTRv2, tag v2-resubmission).", ""]
    d = json.loads((ROOT / "results" / "v2" / "ikincil_analiz_tam.json").read_text(encoding="utf-8"))

    # S1
    labels = _modul("labels", ROOT / "src" / "data" / "labels.py")
    md += ["## Table S1. Taxonomy: ordered keyword rules (first matching rule wins)", "",
           "Keywords are matched as lower-case substrings of the archive folder and file descriptions. "
           "15,356 of 16,008 unique recordings (95.9%) matched a rule; 652 matched none and were excluded. Keywords are listed "
           "exactly as in the code (`src/data/labels.py`); trailing commas, underscores and spaces are part of the "
           "matched strings, which mirror the punctuation of the archive file names.", ""]
    md.append(tablo(["#", "Class", "Keywords"],
                    [(i + 1, EN[c], ", ".join(dict.fromkeys(k.strip() for k in kw))) for i, (c, kw) in
                     enumerate(labels._KURALLAR)]))

    # S2
    md += ["", "## Table S2. First target set (31 May–2 June 2026; single seed, best-validation checkpoint, test)", "",
           "Class-wise F1 change relative to the baseline (baseline F1 in the header). All four classes were augmentation "
           "targets with 50 clips each. These runs used the original pipeline, in which CLAP fine-tuning had no effect "
           "(C2–C4 = pretrained generator). Run `tur2` was repeated on 2 June (`tur2_re`) with identical class-wise F1.", ""]
    dosya = {"H1": "iteratif_loop_1_20260601_1725", "C2": "iteratif_loop_tur2_20260601_2132",
             "C3 (TR)": "iteratif_loop_tur3_20260602_0303", "C4": "iteratif_loop_tur4_20260602_0701"}
    hedef = ["insaat_sesleri", "dini_mekan", "acil_servis", "diger_hayvanlar"]
    taban = None
    satir = []
    for ad, fn in dosya.items():
        j = json.loads((ROOT / "results" / "v1" / f"{fn}.json").read_text(encoding="utf-8"))["cnn"]
        taban = j["baseline"]
        satir.append([ad] + [f(j["augmented"]["sinif_f1"][c] - j["baseline"]["sinif_f1"][c]) for c in hedef]
                     + [f(j["augmented"]["test_f1"], 4, False)])
    re1 = json.loads((ROOT / "results" / "v1" / "iteratif_loop_tur2_re_20260602_1255.json").read_text(encoding="utf-8"))["cnn"]
    re0 = json.loads((ROOT / "results" / "v1" / "iteratif_loop_tur2_20260601_2132.json").read_text(encoding="utf-8"))["cnn"]
    assert re1["augmented"]["sinif_f1"] == re0["augmented"]["sinif_f1"], "tur2_re farkli"
    md.append(tablo(["Config."] + [f"{EN[c]} ({taban['sinif_f1'][c]:.3f})" for c in hedef] + ["Test macro-F1"], satir))

    # S3
    pr = json.loads((ROOT / "data" / "processed" / "turkce_promptlar.json").read_text(encoding="utf-8"))
    md += ["", "## Table S3. Generation prompts (five per class; Turkish and parallel English)", "",
           "Used for generation (assigned cyclically to clips) and as class-level CLAP captions. Most pairs are direct "
           "translations; a few differ in detail.", ""]
    md.append(tablo(["Class", "#", "Turkish", "English"],
                    [(EN[c] if i == 0 else "", i + 1, t, e) for c in pr for i, (t, e) in
                     enumerate(zip(pr[c]["turkce"], pr[c]["ingilizce"]))]))

    # S4
    IL = _modul("il", ROOT / "scripts" / "07_iterative_loop.py")
    tr, vl, te = IL.veri_bol(IL.PARQUET_LISTE, ROOT)
    md += ["", "## Table S4. Real training data and synthetic share per augmented class", "",
           "Each synthetic clip contributes one 5-s training segment. Share = synthetic / (real + synthetic) segments.", ""]
    s4 = []
    for c in AUG:
        n = int(tr[tr.sinif == c].n_segs.sum())
        s4.append((EN[c], len(tr[tr.sinif == c]), n, len(vl[vl.sinif == c]) + len(te[te.sinif == c]),
                   *[f"{100 * k / (n + k):.1f}%" for k in (25, 50, 100, 200)]))
    md.append(tablo(["Class", "Train rec.", "Train seg.", "Val+test rec.", "25 clips", "50", "100", "200"], s4))

    # S5
    md += ["", "## Table S5. Second classifier: frozen BEATs embeddings + MLP (not pre-registered)", "",
           "BEATs iter3+ (AS2M), time-averaged final-layer embeddings of the same segments as the CNN; MLP head with "
           "hyperparameters fixed in advance; final-epoch model; validation + test; recording-level bootstrap.", ""]
    sat = []
    for k in ("beats_baseline", "beats_H1", "beats_C4p"):
        for fj in sorted((ROOT / "results" / "v2" / "siniflandirma").glob(f"{k}_s*.json")):
            j = json.loads(fj.read_text(encoding="utf-8"))
            sat.append((KON[k], j["seed"], f(j["son_epoch"]["val_f1"], 4, False), f(j["son_epoch"]["test_f1"], 4, False)))
    md.append(tablo(["Configuration", "Seed", "Val macro-F1", "Test macro-F1"], sat))
    md.append("")
    md.append(tablo(["Comparison", "Group", "ΔF1", "95% CI", "p"],
                    [(k.split(" - ")[0].replace("beats_", "BEATs ").replace("C4p", "C4′"), GRUP[k.split(" - ")[1]],
                      f(v["delta_f1"]), f"[{f(v['ga95'][0])}, {f(v['ga95'][1])}]", f"{v['p_bootstrap']:.2f}")
                     for k, v in d["beats"]["karsilastirmalar"].items()]))

    # S6
    md += ["", "## Table S6. Memorization analysis (VGGish nearest neighbor)", "",
           "Median nearest-neighbor cosine similarity of synthetic clips to real recordings of their class (syn→real), "
           "of real segments to other recordings of the class (real→real), and share of synthetic clips above the "
           "near-copy threshold (99th percentile of real→real; ~1% of real segments exceed it by construction).", ""]
    s6 = []
    for et in ("H1", "C2p", "C3p", "C4p"):
        z = json.loads((ROOT / "results" / "v2" / f"ezber_analizi_{et}.json").read_text(encoding="utf-8"))["siniflar"]
        for c, v in z.items():
            s6.append((KON[et], EN[c], v["n_sentetik"], f(v["sentetik_gercek_nn_medyan"], 3, False),
                       f(v["gercek_gercek_nn_medyan"], 3, False), f"{100 * v['esigi_asan_sentetik_orani']:.1f}%"))
    md.append(tablo(["Config.", "Class", "Clips", "syn→real", "real→real", "Above threshold"], s6))

    # S7
    md += ["", "## Table S7. Continuity analyses (information only; pre-registered as non-primary)", "",
           "### S7a. Best-validation checkpoint evaluated on the test partition only", ""]
    md.append(tablo(["Comparison", "Group", "ΔF1", "95% CI", "p"],
                    [(f"{KON[x['test']]} − {KON[x['referans']]}", GRUP[x["grup"]], f(x["delta_f1"]),
                      f"[{f(x['ga95'][0])}, {f(x['ga95'][1])}]", f"{x['p_bootstrap']:.3f}")
                     for x in d["sureklilik_enIyiVal_test"]]))
    BA = _modul("ba", ROOT / "scripts" / "16_birincil_analiz.py")
    gt, kayit, tah = BA.v2_yukle(["baseline", "H1", "C2p", "C3p", "C4p"], "son_valtest")
    ixA = np.isin(gt, [BA.SINIF_SIRASI.index(c) for c in BA.GRUPLAR["A_belirgin"]])
    s7b = []
    for k in ("H1", "C2p", "C3p", "C4p"):
        for sd in sorted(set(tah[k]) & set(tah["baseline"])):
            a, b = tah["baseline"][sd][ixA] == gt[ixA], tah[k][sd][ixA] == gt[ixA]
            n01, n10 = int((a & ~b).sum()), int((~a & b).sum())
            x2 = (abs(n01 - n10) - 1) ** 2 / (n01 + n10) if n01 + n10 else 0.0
            s7b.append((KON[k], sd, n10, n01, f"{x2:.2f}", pfmt(chi2.sf(x2, 1))))
    md += ["", "### S7b. Segment-level McNemar tests (Group A segments, final-epoch model, validation + test; "
               "Yates correction). Segments of the same recording are not independent, so these p-values are not valid "
               "inference and are shown only for continuity with the original submission.", ""]
    md.append(tablo(["Config. vs baseline", "Seed", "Only config. correct", "Only baseline correct", "χ²", "p"], s7b))
    v1 = json.loads((ROOT / "results" / "v1" / "birincil_analiz_v1.json").read_text(encoding="utf-8"))
    md += ["", "### S7c. Original (v1) predictions re-analyzed at the recording level (Group A; single seed; test)", ""]
    md.append(tablo(["Comparison", "ΔF1", "95% CI", "p", "p (Holm)"],
                    [(f"{k['test']} − {k['referans']}", f(k["gruplar"]["A_belirgin"]["delta_f1"]),
                      f"[{f(k['gruplar']['A_belirgin']['ga95'][0])}, {f(k['gruplar']['A_belirgin']['ga95'][1])}]",
                      f"{k['gruplar']['A_belirgin']['p_bootstrap']:.3f}", f"{k['gruplar']['A_belirgin'].get('p_holm', float('nan')):.2f}")
                     for k in v1["karsilastirmalar"] if "A_belirgin" in k["gruplar"]]))

    # S8
    c = json.loads((ROOT / "results" / "v2" / "hesaplama_maliyeti.json").read_text(encoding="utf-8"))
    md += ["", "## Table S8. Computational cost (single NVIDIA RTX 3060, 12 GB)", ""]
    md.append(tablo(["Item", "Unit cost", "Total"], [
        ("CLAP fine-tuning (2 cycles × 10 epochs)", f"{np.mean([v['epoch_basina_dk_medyan'] for v in c['clap_ince_ayar'].values()]):.0f} min/epoch",
         f"{sum(v['toplam_saat'] for v in c['clap_ince_ayar'].values()):.1f} h"),
        ("Generation (AudioLDM2-full, 200 DDIM steps)", f"{c['uretim']['klip_basina_sn_medyan']:.0f} s/clip",
         f"{c['uretim']['toplam_klip'] * c['uretim']['klip_basina_sn_medyan'] / 3600:.1f} h ({c['uretim']['toplam_klip']} clips)"),
        ("ResNet-18 training (30 epochs)", f"{c['resnet18']['kosu_basina_dk_medyan'] / 60:.1f} h/run",
         f"{c['resnet18']['toplam_saat']:.1f} h ({c['resnet18']['n_kosu']} runs)"),
        ("BEATs embedding extraction + MLP heads", f"{c['beats']['kafa_basina_dk_medyan']:.1f} min/head",
         f"{(c['beats']['gomme_dk'] + c['beats']['kafa_basina_dk_medyan'] * c['beats']['n_kafa']) / 60:.1f} h"),
        ("**Total**", "", f"**≈{c['toplam_gpu_saat_yaklasik']:.0f} GPU-hours**")]))

    cikti = ROOT / "results" / "v2" / "ek_tablolar.md"
    cikti.write_text("\n".join(md) + "\n", encoding="utf-8")
    print("kaydedildi:", cikti, f"({len(md)} satir)")


if __name__ == "__main__":
    main()
